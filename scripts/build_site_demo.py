#!/usr/bin/env python3
"""Regenerate the site's real artifacts from a real `--demo` run.

    python scripts/build_site_demo.py

Runs the actual controller — real worktrees, real pytest and ruff gates, the
scripted critic from demo/fake_claude.py — and writes:

  site/report.html     that run's RUN_REPORT.html, with a "sample" banner
  site/arena-data.js   the tournament, compacted, for the home page's arena

Nothing on the site is hand-typed: change the report renderer or the demo
story, re-run this, and the site shows what the code now does.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
# Inside the repo (runs/ is gitignored) so the report's checkout commands show
# a short relative path rather than a temp directory.
RUNS = ROOT / "runs" / "_site-demo"

BANNER = (
    '<section class="card" style="padding:14px 16px;display:flex;gap:12px;align-items:center;'
    'flex-wrap:wrap"><span class="sim">sample</span><span style="flex:1;min-width:220px">'
    "This is the real <code>RUN_REPORT.html</code> from <code>python crucible.py --demo</code>: "
    "real worktrees and real gates, a scripted critic, no API calls.</span>"
    '<a href="/" style="color:var(--accent)">← back to the CRUCIBLE site</a></section>'
)


def main() -> int:
    shutil.rmtree(RUNS, ignore_errors=True)
    env = {**os.environ, "CRUCIBLE_RUNS_DIR": str(RUNS), "CRUCIBLE_DEMO_PACE": "0", "NO_COLOR": "1"}
    proc = subprocess.run(
        [sys.executable, str(ROOT / "crucible.py"), "--demo"],
        cwd=ROOT, env=env, capture_output=True, text=True,
    )  # fmt: skip
    if proc.returncode != 0:
        print(proc.stdout + proc.stderr, file=sys.stderr)
        return 1
    run_dir = next(p for p in RUNS.iterdir() if p.is_dir())
    state = json.loads((run_dir / "state.json").read_text(encoding="utf-8"))

    page = (run_dir / "RUN_REPORT.html").read_text(encoding="utf-8")
    page = page.replace("<head>", '<head>\n<meta name="robots" content="noindex">', 1)
    page = page.replace('<div class="wrap">\n', '<div class="wrap">\n' + BANNER + "\n", 1)
    (SITE / "report.html").write_text(page, encoding="utf-8")

    rounds = []
    for h in state["history"]:
        cands = []
        for c in h["candidates"]:
            cand_dir = run_dir / "rounds" / f"round_{h['round']}" / f"cand_{c['id']}"
            crit_path = cand_dir / "critique.json"
            crit = json.loads(crit_path.read_text()) if crit_path.is_file() else None
            cands.append({
                "id": c["id"], "angle": c["angle"], "status": c["status"],
                "gates": c["gates_passed"], "score": c["min_score"], "verdict": c["verdict"],
                "cost": c["cost_usd"],
                "scores": crit["scores"] if crit else None,
                "mustFix": len(crit["must_fix"]) if crit else None,
            })  # fmt: skip
        rounds.append(
            {"n": h["round"], "winner": h["winner"], "cost": h["cost_usd"], "cands": cands}
        )
    data = {
        "runId": state["run_id"], "stopReason": state["stop_reason"],
        "bestRound": state["best_round"], "bestScore": state["best_overall"],
        "totalCost": round(state["total_cost_usd"], 4), "budget": state["budget_usd"],
        "threshold": state["pass_threshold"], "rounds": rounds,
    }  # fmt: skip
    (SITE / "arena-data.js").write_text(
        "/* Generated by scripts/build_site_demo.py from a real `crucible.py --demo` run. */\n"
        f"window.CRUCIBLE_DEMO = {json.dumps(data, indent=1)};\n",
        encoding="utf-8",
    )
    shutil.rmtree(RUNS, ignore_errors=True)
    print(f"wrote site/report.html and site/arena-data.js from {state['run_id']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
